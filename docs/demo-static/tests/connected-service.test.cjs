const assert=require('node:assert/strict');
const harness=require('./prototype-harness.cjs');
const {run,elements}=harness();
run("csAction('cs-start','')");
assert(elements['#main'].innerHTML.includes('诊后患者统一视图'));
assert.equal(run('ccPlans().length'),1);
assert(run('csSummary()').includes('原台账未结问题'));
assert.equal(run('csOtherIssues(patient(1001)).length'),2);
run("csAction('cs-start','')");
assert.equal(run('ccPlans().length'),1,'sample entry is idempotent');
assert(!run('csPhone(patient(1001))').includes('演示患者一'),'registration gate hides patient data');
run("csAction('cs-verify',1001,{evidence:'本人和绑定关系已人工核实'})");
assert(run('csGranted(patient(1001))'));
assert(!run('csPhone(patient(1001))').includes('请按已核对的原医嘱执行'));
run("ccAction('cc-approve',1001,{evidence:'运营代审不得生效'})");
assert.equal(run('ccPlans()[0].approval'),'PENDING');
run("account=person(2);ccAction('cc-approve',1001,{evidence:'责任医生确认'})");
assert(run('csPhone(patient(1001))').includes('请按已核对的原医嘱执行'));
run("csAction('cs-feedback',1001,{kind:'CLINICAL',note:'虚构患者临床问题'})");
assert.equal(run('acCases().find(c=>c.id===1001).issues.length'),1,'feedback uses existing case queue');
run("account=person(4);acAction('ac-accept','1001:0',{note:'运营不能接受临床处置'})");
assert(!run('acCases().find(c=>c.id===1001).issues[0].accepted'));
run("account=person(2);acAction('ac-accept','1001:0',{note:'医生本人接单'});acAction('ac-resolve','1001:0',{note:'内部记录不应公开'})");
assert(!run('csPhone(patient(1001))').includes('内部记录不应公开'));
run("account=person(4);csAction('cs-reply','1001:1001:0',{reply:'运营不能发布临床意见'})");
assert(!run('acCases().find(c=>c.id===1001).issues[0].patientReply'));
run("account=person(2);csAction('cs-reply','1001:1001:0',{reply:'医生明确发布的下一步'})");
assert(run('csPhone(patient(1001))').includes('医生明确发布的下一步'));
assert(!run('acCases().find(c=>c.id===1001).issues[0].closed'),'publishing does not close feedback');
run("account=person(4);acAction('ac-resolve','1001:0',{note:'核实患者已获得反馈'})");
assert(run('csPhone(patient(1001))').includes('已核验关闭'));
assert(run('csSummary()').includes('尚无独立到院证据'));

// Renewals invalidate old entries and clinical approval must use current consent.
run("csAction('cs-issue',1001,{contact:'DEMO-WECOM-1001',evidence:'续签同一联系人'})");
assert(run('csState().entries[0].revoked'));
assert(!run('csValid(csState().entries[0])'));
assert(!run('csPhone(patient(1001))').includes('医生明确发布的下一步'));
run("csAction('cs-register',1001,{name:'虚构本人',relation:'SELF',consent:'YES'});csAction('cs-verify',1001,{evidence:'重新核实'})");
assert(!run('ccApproved(ccPlans()[0],patient(1001))'));
assert(!run('csPhone(patient(1001))').includes('请按已核对的原医嘱执行'));
assert(run('csPhone(patient(1001))').includes('医生明确发布的下一步'),'same contact retains own feedback');
run("account=person(2);ccAction('cc-approve',1001,{evidence:'按新授权重新审核'});ccAction('cc-review',1001,{date:'2026-12-01',message:'阶段结果',evidence:'虚构复盘'})");
assert(run('csPhone(patient(1001))').includes('阶段结果'));
run("ccAction('cc-reject',1001,{evidence:'补充资料再审'})");
assert(!run('csPhone(patient(1001))').includes('阶段结果'));
run("account=person(4);csAction('cs-issue',1001,{contact:'DEMO-OTHER-FAMILY',evidence:'新的家属联系人'});csAction('cs-register',1001,{name:'另一位家属',relation:'FAMILY',consent:'YES'});csAction('cs-verify',1001,{evidence:'人工核实代办关系和授权范围'})");
assert(!run('csPhone(patient(1001))').includes('医生明确发布的下一步'),'other family has separate feedback');
run("csAction('cs-withdraw',1001,{evidence:'患者自主撤回'})");
assert(!run('patient(1001).service_consent'));
assert(!run('csGranted(patient(1001))'));
assert.equal(run('acCases().find(c=>c.id===1001).status'),'WITHDRAWN');
const count=run('acCases().find(c=>c.id===1001).issues.length');
run("csAction('cs-feedback',1001,{kind:'SERVICE',note:'撤回后禁止新增'})");
assert.equal(run('acCases().find(c=>c.id===1001).issues.length'),count);

// Role, patient and date boundaries, without mutating the existing entry/plan.
run("account=person(6);location.hash='#/after-care?tab=summary&patient=1001';render()");
assert(elements['#main'].innerHTML.includes('无权访问'));
run("csAction('cs-issue',1001,{contact:'DENIED',evidence:'跨范围禁止'})");
assert.notEqual(run('csEntry(patient(1001)).contact'),'DENIED');
run("account=person(5);location.hash='#/after-care?tab=summary&patient=1001';render()");
assert(!elements['#main'].innerHTML.includes('演示患者一'));
const h=harness();
h.run("account=person(1);location.hash='#/after-care?tab=continuity&patient=1002';render();ccAction('cc-save',1002,{baseline:'资料',goals:'目标',instructions:'说明',date:'2026-02-30',evidence:'日期错误'})");
assert.equal(h.run('ccPlans().length'),0);
h.run("ccAction('cc-save',1002,{baseline:'资料',goals:'目标',instructions:'说明',date:'2026-99-99',evidence:'日期错误'})");
assert.equal(h.run('ccPlans().length'),0);
h.run("csAction('cs-issue',1002,{contact:'<img src=x onerror=alert(1)>',evidence:'仅转义显示'});location.hash='#/wecom?tab=service&patient=1002';render()");
assert(!h.elements['#main'].innerHTML.includes('<img src=x'));
h.run("csEntry(patient(1002)).expires='2000-01-01';csAction('cs-register',1002,{name:'过期',relation:'SELF',consent:'YES'})");
assert.equal(h.run('csEntry(patient(1002)).status'),'ISSUED');
h.run("csAction('cs-context','',{tab:'service',patient:1003})");
assert.equal(h.run('current.path'),'/wecom');
assert.equal(h.run("current.query.get('patient')"),'1003');
console.log('PASS: shared service/summary/plan state, doctor-only clinical workflow, private/public replies, renewal and current consent, contact isolation, expiry, withdrawal, role scope, invalid dates and escaping.');
